"""
Проверка «пишет как человек» (voice.md). Ловит то, по чему в мессенджере сразу узнают бота
или канцелярию. Вызывается из wa_send.py для всех сообщений; правила H* в выводе.
"""

import re

BOT_PHRASES = [
    (r"благодарим\b", "«Благодарим» → «Спасибо!»"),
    (r"уважаем(ый|ая|ые)\b", "«Уважаемый» → по имени или без обращения"),
    (r"\bданн(ый|ого|ому|ом|ая|ую|ой|ое|ые|ых)\b", "«данный» → «этот»"),
    (r"\bв рамках\b", "«в рамках» → проще"),
    (r"\bосуществл", "«осуществлять» → «делать»"),
    (r"\bпредоставл", "«предоставлять» → «давать / присылать»"),
    (r"будем рады", "«будем рады …» не писать"),
    (r"надеемся на", "«надеемся на …» не писать"),
    (r"не стесняйтесь", "«не стесняйтесь» → «если что, пишите»"),
    (r"с уважением", "подпись «С уважением» в мессенджере не нужна"),
    (r"команда профессионал|лидер(ы|ов)? рынка", "самореклама не нужна"),
    (r"обратн(ую|ой) связ", "«обратная связь» → «ответ»"),
    (r"по вопросам сотрудничества", "канцелярит"),
    (
        r"индивидуальн\w* подход|рассчитывается индивидуально",
        "«индивидуально» → «зависит от задачи»",
    ),
    # Обороты, по которым сразу узнают нейросеть (практика, не измерение).
    (r"отличный вопрос|хороший вопрос", "«отличный вопрос» — привычка нейросети, просто ответить"),
    (
        r"надеюсь, (это|мой ответ|информация) (помо|было|будет)",
        "«надеюсь, это поможет» — привычка нейросети",
    ),
    (r"\bрад(а)? помочь\b", "«рад помочь» — так пишет бот поддержки"),
    (
        r"я понимаю ваш(и|у) (опасени|сомнени|озабоченност)",
        "«понимаю ваши опасения» → «понимаю» или по сути",
    ),
    (r"(стоит|хочу|важно) отметить", "«стоит отметить» → сказать прямо"),
    (r"\bв заключение\b|\bподводя итог", "«в заключение» — так пишут статьи, не сообщения"),
    (
        r"впечатлил|восхищ|(отличн|замечательн|прекрасн)\w* (компани|сайт|работ)",
        "общий комплимент — сразу видно шаблон; лучше конкретная деталь о них",
    ),
    (r"если (у вас )?(возникнут|появятся|остались) (какие-либо |ещё |еще )?вопрос",
     "«если возникнут вопросы» → «если что, пишите»"),
]

EMOJI = re.compile("[\U0001F300-\U0001FAFF\u2600-\u27BF]")

MAX_REPLY_WORDS = 50
# Первые слова видно в уведомлении, поэтому начинать с их компании, а не с себя.
# Подтверждено косвенно: Gong Labs — упоминание конкретной компании утраивает ответы
# руководителей; Hunter 2026 — +56% ответов у писем с двумя персональными деталями.
# Порог 80 символов — наша практика, не измеренная цифра.
PREVIEW = 80
SELF_INTRO = re.compile(
    r"меня зовут|я из компании|компания camirix|представляю компанию", re.IGNORECASE
)


# 38-ФЗ «О рекламе», ст. 18: реклама по почте и в мессенджерах — только с согласия. Личное деловое
# предложение конкретной компании рекламой быть перестаёт, если в нём нет рекламных приёмов.
PROMO = re.compile(
    r"\bскидк|\bакци(я|и|ю|ей)\b|\bуспейте\b|только сегодня|спецпредложени|\bпромокод"
    r"|выгодн\w* предложени|\bраспродаж|\bдо конца (недели|месяца)\b"
)


def words(text):
    return len(re.findall(r"[\wЀ-ӿ]+", text or ""))


# Приветствие не по времени адресата («Доброе утро» в 15:00) сразу выдаёт рассылку.
MORNING = re.compile(r"доброе утро")
EVENING = re.compile(r"добрый вечер")
NICE_DAY = re.compile(r"хорошего дня")
# Незнакомому человеку по делу — на «вы», даже если он пишет на «ты».
TY = re.compile(r"\b(ты|тебе|тебя|тобой|твой|твоя|твоё|твое|твои|твоих)\b")


def check(text, kind="first", their_text="", local_hour=None):
    """→ список замечаний (пусто — звучит по-человечески).
    local_hour — час у адресата (0–23), если известен: проверяется приветствие."""
    t = (text or "").strip()
    low = t.lower()
    out = []
    for rx, why in BOT_PHRASES:
        if re.search(rx, low):
            out.append(f"H1 {why}")
    if t.count("!") > 1 or "!!" in t:
        out.append("H2 больше одного «!»: звучит как реклама")
    if kind == "reply":
        n = words(t)
        limit = MAX_REPLY_WORDS
        if their_text:
            limit = min(MAX_REPLY_WORDS, max(25, 2 * words(their_text)))
        if n > limit:
            out.append(
                f"H3 ответ {n} слов при лимите {limit}: в мессенджере отвечают коротко, "
                "не длиннее их сообщения вдвое"
            )
    if kind == "first" and SELF_INTRO.search(t[:PREVIEW]):
        out.append(
            "H7 первые 80 символов (их видно в уведомлении) ушли на представление: начать с "
            "того, что касается их («Вижу, что вы ищете…»), а кто пишет — после"
        )
    if re.search(r"\[[^\]]*\]|\{[^}]*\}|…|<[^>]+>", t):  # «…» в шаблонах — место для текста
        out.append("H4 в тексте остался незаполненный шаблон")
    if re.search(r"\*\*|^#|^\s*([-•*]|\d+[.)])\s", t, re.MULTILINE):
        out.append("H9 списки и разметка (**, #, «- », «1.»): в мессенджере так не пишут")
    if len(EMOJI.findall(t)) > 1:
        out.append("H10 больше одного эмодзи: с незнакомым человеком по делу максимум один")
    if PROMO.search(low):
        out.append(
            "H8 рекламный приём (скидка, акция, «успейте»): писать как личное деловое "
            "предложение этой компании, без призывов (38-ФЗ ст. 18)"
        )
    if TY.search(low):
        out.append("H11 на «ты»: незнакомому человеку по делу пишут на «вы»")
    if local_hour is not None:
        if MORNING.search(low) and local_hour >= 12:
            out.append(f"H12 «доброе утро», а у адресата {local_hour}:00 → «добрый день»")
        if EVENING.search(low) and local_hour < 17:
            out.append(f"H12 «добрый вечер», а у адресата {local_hour}:00 → «добрый день»")
        if NICE_DAY.search(low) and local_hour >= 17:
            out.append(f"H12 «хорошего дня», а у адресата {local_hour}:00 → «хорошего вечера»")
    if len(re.findall(r"(?i)\bподскажите\b", t)) > 1:
        out.append("H5 «подскажите» дважды в одном сообщении")
    return out
